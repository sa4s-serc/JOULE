"""Scaffold a new JOULE operator plugin.

Generates the minimal files needed to build and register a custom
operator, including a pyproject.toml entry point snippet.
"""

from __future__ import annotations

from pathlib import Path
from textwrap import dedent


_OPERATOR_TEMPLATE = '''\
"""
{class_name}: JOULE operator plugin.

Auto-generated by: joule scaffold-operator
Tier: {tier}
Targets smell categories: {smells}

Edit this file to implement your transformation logic.
See https://joule.readthedocs.io/plugin-sdk for the full guide.
"""

from __future__ import annotations

from joule.plugin_sdk import BaseOperator, SearchContext, TargetSpec, Tier, TransformationResult


class {class_name}(BaseOperator):
    """One-line description of what this operator does."""

    name = "{operator_name}"
    family = "deterministic"
    tier = Tier.{tier}
    escape_only = False
    # Energy-Smells taxonomy categories this operator primarily targets.
    # Run `joule transformations` to see which smells map to which operators.
    targets_smells = frozenset({{{smells_literal}}})

    def generate(
        self,
        target: TargetSpec,
        context: SearchContext | None = None,
    ) -> list[TransformationResult]:
        """Apply the transformation and return candidate variants.

        Parameters
        ----------
        target:
            The target function specification including ``target.source``
            (the full Python source of the function) and ``target.qualname``.
        context:
            Optional search context carrying generation depth, parent id,
            smell tags, and prior rejection history.

        Returns
        -------
        list[TransformationResult]
            Zero or more candidate variants.  Return an empty list when the
            transformation is not applicable to this target.
        """
        source = target.source
        # TODO: implement your transformation here.
        # When no transformation applies, return [].
        # Example:
        #   new_source = source.replace("something", "something_better")
        #   if new_source == source:
        #       return []
        #   return [self.build_result(
        #       candidate_source=new_source,
        #       reasoning="replaced something with something_better",
        #   )]
        del source, context
        return []
'''

_PYPROJECT_SNIPPET = """\
# Add to your pyproject.toml to register the operator:
# [project.entry-points."joule.operators"]
# {operator_name} = "{package}.{module_name}:{class_name}"
"""

_TEST_TEMPLATE = '''\
"""Tests for {class_name} operator."""

from __future__ import annotations

from pathlib import Path

import pytest

from {package}.{module_name} import {class_name}
from joule.models import TargetSpec


@pytest.fixture()
def target(tmp_path: Path) -> TargetSpec:
    source = """def example(items):
    result = []
    for item in items:
        result.append(item * 2)
    return result
"""
    module = tmp_path / "example.py"
    module.write_text(source, encoding="utf-8")
    return TargetSpec(
        project_root=tmp_path,
        module="example",
        file_path=module,
        function_name="example",
        qualname="example",
        owner_path=[],
        source=source,
        is_async=False,
    )


def test_{snake_name}_generates_candidates(target: TargetSpec) -> None:
    op = {class_name}()
    results = op.generate(target)
    # TODO: update this assertion once the transformation is implemented.
    # When the operator produces results, check that sources differ.
    for result in results:
        assert result.candidate_source != target.source
        assert result.operator_name == op.name


def test_{snake_name}_empty_on_irrelevant_source(tmp_path: Path) -> None:
    """Operator should return [] when transformation does not apply."""
    source = "def noop(): pass\\n"
    module = tmp_path / "noop.py"
    module.write_text(source, encoding="utf-8")
    spec = TargetSpec(
        project_root=tmp_path,
        module="noop",
        file_path=module,
        function_name="noop",
        qualname="noop",
        owner_path=[],
        source=source,
        is_async=False,
    )
    op = {class_name}()
    results = op.generate(spec)
    # Simple functions should not be transformed; adjust if your operator
    # handles trivially simple sources differently.
    assert isinstance(results, list)
'''


def _to_pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.replace("-", "_").split("_"))


def run_scaffold_operator(
    *,
    name: str,
    tier: str,
    smells: list[str],
    output: Path,
    package: str,
) -> None:
    """Generate scaffold files for a new operator plugin.

    Parameters
    ----------
    name:
        Operator name in snake_case (e.g. ``my_optimizer``).
    tier:
        Tier string: ``L``, ``M``, or ``H``.
    smells:
        List of Energy-Smell categories targeted (e.g. ``["C3", "C10"]``).
    output:
        Directory where the files are written.
    package:
        Python package name for the generated module (used in entry-point
        snippet and test imports).
    """
    from typer import echo

    tier_upper = tier.strip().upper()
    if tier_upper not in ("L", "M", "H"):
        raise ValueError(f"Invalid tier {tier!r}. Must be one of: L, M, H")

    class_name = _to_pascal(name) + "Operator"
    module_name = name.lower().replace("-", "_")
    smells_literal = ", ".join(f'"{s}"' for s in sorted(smells))

    output.mkdir(parents=True, exist_ok=True)

    # Write operator module
    operator_path = output / f"{module_name}.py"
    operator_path.write_text(
        _OPERATOR_TEMPLATE.format(
            class_name=class_name,
            operator_name=name,
            tier=tier_upper,
            smells=", ".join(sorted(smells)) if smells else "(none)",
            smells_literal=smells_literal,
        ),
        encoding="utf-8",
    )

    # Write test module
    test_path = output / f"test_{module_name}.py"
    test_path.write_text(
        _TEST_TEMPLATE.format(
            class_name=class_name,
            operator_name=name,
            module_name=module_name,
            package=package,
            snake_name=module_name,
        ),
        encoding="utf-8",
    )

    # Write pyproject snippet
    snippet_path = output / "pyproject_snippet.txt"
    snippet_path.write_text(
        _PYPROJECT_SNIPPET.format(
            operator_name=name,
            package=package,
            module_name=module_name,
            class_name=class_name,
        ),
        encoding="utf-8",
    )

    echo(f"✓ Operator scaffolded in {output}")
    echo(f"  {operator_path.relative_to(output.parent)}")
    echo(f"  {test_path.relative_to(output.parent)}")
    echo(f"  {snippet_path.relative_to(output.parent)}")
    echo(f"\nNext steps:")
    echo(f"  1. Edit {operator_path.name} to implement your transformation")
    echo(f"  2. Run: pytest {test_path.name}")
    echo(f"  3. Add the entry point from {snippet_path.name} to your pyproject.toml")
    echo(f"  4. Run: joule doctor --plugin-check")
